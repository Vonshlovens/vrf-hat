// Copies the compiled RaffleDraw ABI into the app as a typed constant.
import { readFile, writeFile } from "node:fs/promises";

const artifact = JSON.parse(
  await readFile(
    new URL("../artifacts/contracts/RaffleDraw.sol/RaffleDraw.json", import.meta.url),
    "utf8",
  ),
);
const out = new URL("../../src/lib/chain/raffle-draw-abi.ts", import.meta.url);
await writeFile(
  out,
  `// Generated by contracts/scripts/export-abi.ts. Do not edit.\nexport const raffleDrawAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
);
console.log(`Wrote ${out.pathname}`);
